// Language names sent to the AI so it writes in the child's language.
export const LANGUAGE_NAMES = { en: 'English', es: 'Spanish', fr: 'French', de: 'German' };

export function detectUserLanguage() {
  // 1) Saved preference (optional override)
  try {
    const saved = localStorage.getItem('curiocity_lang');
    if (saved && translations[saved]) return saved;
  } catch {
    // localStorage may be blocked (private mode); ignore
  }

  // 2) Browser language preferences, in order
  const candidates = [...(navigator.languages || []), navigator.language];
  try {
    candidates.push(Intl.DateTimeFormat().resolvedOptions().locale);
  } catch {
    // ignore
  }
  for (const lang of candidates) {
    const code = String(lang || '').split('-')[0].toLowerCase();
    if (translations[code]) return code;
  }
  return 'en';
}
